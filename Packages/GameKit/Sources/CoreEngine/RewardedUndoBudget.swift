import Foundation

/// 「戻す」の回数制（#476 でソリティアに入れた経済を、フリーセル #492 と共有するために Core へ上げた）。
///
/// **1 か所に持つ理由**: 2 つのゲームが別々に定数を持つと、片方だけ調整したときに
/// 「同じ操作なのにゲームによって無料回数が違う」状態が静かに生まれる。#492 の仕様が
/// 「定数を共有し、経済を揃える」と明示しているのはこの型のこと。
///
/// ゲーム側の名前（`SolitaireUndoBudget` 等）はここへ転送するだけにして、
/// 呼び出し側の表記は各ゲームの文脈に残す。
public enum RewardedUndoBudget {
    /// 1 局につき無料で戻せる回数。配り直し・新規ゲームでここまで戻る。
    public static let free = 3
    /// リワード広告 1 本の視聴完了で補充する回数。
    public static let refill = 3
}
