    private static let images: [ObjectCardKind: CGImage] = {
        var out: [ObjectCardKind: CGImage] = [:]
        for kind in allCases { if let cg = kind.sprite.cgImage(scale: 2) { out[kind] = cg } }
        return out
    }()

    public var cgImage: CGImage? { Self.images[self] }
