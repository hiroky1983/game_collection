    static func decode(_ text: String) -> [SpiderMove] {
        text.split(separator: " ").compactMap { token in
            if token == "D" { return .deal }
            let parts = token.split(separator: ".").compactMap { Int($0) }
            guard parts.count == 3 else { return nil }
            return .move(from: parts[0], cardIndex: parts[1], to: parts[2])
        }
    }

    @Test("種 704 は保存した勝ち筋を指し切ればクリアできる")
    func seed704IsWinnable() {
        #expect(SpiderDealer.verifiedSeeds(for: .four).contains(704))
        var board = SpiderDealer.deal(seed: 704, suits: .four)
        let moves = Self.decode(Self.seed704)
        #expect(moves.count == 290)
        #expect(moves.filter { $0 == .deal }.count == 5, "配りは 5 回すべて含む")
        for (index, move) in moves.enumerated() {
            let applied = board.apply(move)
            #expect(applied, "\(index) 手目 \(move) が適用できない")
            if !applied { return }
        }
        #expect(board.isWon)
    }

