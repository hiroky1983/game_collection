    private func assertWinnable(seed: UInt64, solution: String, moveCount: Int) {
        #expect(SpiderDealer.verifiedSeeds(for: .four).contains(seed))
        var board = SpiderDealer.deal(seed: seed, suits: .four)
        let moves = Self.decode(solution)
        #expect(moves.count == moveCount)
        #expect(moves.filter { $0 == .deal }.count == 5, "配りは 5 回すべて含む")
        for (index, move) in moves.enumerated() {
            let applied = board.apply(move)
            #expect(applied, "\(index) 手目 \(move) が適用できない")
            if !applied { return }
        }
        #expect(board.isWon)
    }

